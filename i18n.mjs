//   node server.mjs --steam --lang zh-CN
//   $env:IFZ_MCP_LANG = "ja"; node server.mjs --steam
//
// 支持：en（默认，原始英文描述）、zh-CN、ja、ru。
// 未翻译的工具会回退到英文原文；参数（.describe）保持英文以避免 schema 不一致。

